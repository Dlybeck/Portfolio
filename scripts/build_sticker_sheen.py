"""Bake the matte sheen of each cover sticker into a static overlay picture.

A real sticker is matte: a soft top-left light, a faint broad brightening and a slightly raised edge.
Doing that with an SVG lighting filter re-runs it every frame, so it is rendered here once instead:

  1. each sticker is photographed on a black and on a white cover (the classic matte trick), which gives
     its exact alpha, including the stamp's perforations, rounded corners and the name tag's curled corner;
  2. the alpha is lit the way the old `feDiffuseLighting` filter did (blur 3, surface scale 2.5, a white
     point light at -60,-80,320 above the sticker's top-left corner);
  3. the result is a white picture whose alpha is the light's strength times the sticker's own alpha, so
     it can never paint outside the sticker. It is laid over the sticker with ordinary compositing: no
     blend mode, no filter, nothing to compute while the page runs.

Writes static/img/notebook/sheen/<sticker>.png and the rules that place them (between the sheen markers in
static/css/notebook/stickers.css). Run it again after a sticker's shape or size changes:

    python scripts/build_sticker_sheen.py          # every sticker on the cover's front
    python scripts/build_sticker_sheen.py cow now  # just these (the other overlays and rules are kept)

Needs Pillow, NumPy and Playwright with Chromium (the dev requirements, plus numpy).
"""

from __future__ import annotations

import io
import socket
import sys
import threading
import time
from pathlib import Path

import numpy as np
import uvicorn
from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from main import app  # noqa: E402

OUT = ROOT / "static" / "img" / "notebook" / "sheen"
CSS = ROOT / "static" / "css" / "notebook" / "stickers.css"
BEGIN, END = "/* sheen:begin (generated by scripts/build_sticker_sheen.py) */", "/* sheen:end */"

# Stickers that are a fixed shape, by CSS class (.wd-<name>); the order is the order of the generated rules. The blank one holds
# whatever shape the visitor picks, so it gets none. "name" now sits on the inside front cover, which this script does not
# photograph: its overlay stays as it is (and so does its rule) until its shape changes.
STICKERS = ["name", "now", "hike", "scan", "puzzle", "p12", "ball", "cow"]
ON_FRONT = [n for n in STICKERS if n != "name"]

SCALE = 2  # render at 2x so the overlay stays crisp on retina screens
BLUR, SURFACE, LIGHT = 3.0, 2.5, (-60.0, -80.0, 320.0)  # the old #wd-matte filter, in CSS pixels
PAD = 16  # CSS px of empty margin so the blur and the raised edge see the sticker's outline


def gaussian(a: np.ndarray, sigma: float) -> np.ndarray:
    r = int(sigma * 3) + 1
    k = np.exp(-0.5 * (np.arange(-r, r + 1) / sigma) ** 2)
    k /= k.sum()
    for axis in (0, 1):
        a = np.apply_along_axis(lambda v: np.convolve(v, k, mode="same"), axis, a)
    return a


def sheen(alpha: np.ndarray) -> np.ndarray:
    """RGBA (white, light strength x sticker alpha) for a sticker's alpha map, 0..1, at SCALE x."""
    h, w = alpha.shape
    pad = PAD * SCALE
    a = np.pad(alpha, pad)
    height = gaussian(a, BLUR * SCALE)
    p = np.pad(height, 1, mode="edge")
    sobel_x = (p[:-2, 2:] + 2 * p[1:-1, 2:] + p[2:, 2:]) - (p[:-2, :-2] + 2 * p[1:-1, :-2] + p[2:, :-2])
    sobel_y = (p[2:, :-2] + 2 * p[2:, 1:-1] + p[2:, 2:]) - (p[:-2, :-2] + 2 * p[:-2, 1:-1] + p[:-2, 2:])
    # slopes per CSS pixel, as the filter has them (a finer grid has smaller per-pixel steps)
    nx = -SURFACE * sobel_x / 4 * SCALE
    ny = -SURFACE * sobel_y / 4 * SCALE
    ys, xs = np.mgrid[0 : a.shape[0], 0 : a.shape[1]]
    lx = LIGHT[0] - (xs - pad) / SCALE
    ly = LIGHT[1] - (ys - pad) / SCALE
    lz = LIGHT[2] - SURFACE * height
    norm_n = np.sqrt(nx**2 + ny**2 + 1)
    norm_l = np.sqrt(lx**2 + ly**2 + lz**2)
    lit = np.clip((nx * lx + ny * ly + lz) / (norm_n * norm_l), 0, 1)
    strength = np.clip(0.5 * lit - 0.34, 0, 1)  # the filter's feColorMatrix
    out = (strength * a)[pad : pad + h, pad : pad + w]
    rgba = np.empty((h, w, 4), np.uint8)
    rgba[..., :3] = 255
    rgba[..., 3] = np.rint(out * 255).astype(np.uint8)
    return rgba


def shoot(page, name: str, backdrop: str) -> tuple[np.ndarray, dict]:
    """The sticker alone, upright and unfiltered, on a flat backdrop, cropped to its own box."""
    page.add_style_tag(
        content=f"""
        .cover-front {{ background: {backdrop} !important; }}
        .cover-front::before, .cover-front::after {{ display: none !important; }}
        .cover-front * {{ visibility: hidden !important; }}
        .cover-front .wd-{name}, .cover-front .wd-{name} * {{ visibility: visible !important; }}
        .cover-front .wd-slot {{ rotate: none !important; scale: none !important; }}
        .cover-front .wd-{name} {{ rotate: none !important; scale: none !important; filter: none !important; }}
        .cover-front .wd-{name} .wd-sh, .cover-front .wd-{name} .wd-mt {{ display: none !important; }}
        .cover-front *, .cover-front *::before, .cover-front *::after {{ animation: none !important; transition: none !important; }}
        """
    )
    page.wait_for_timeout(150)
    el = page.locator(f".cover-front .wd-{name}")
    info = el.evaluate(
        """e => { const r = e.getBoundingClientRect(), c = getComputedStyle(e);
          return { x: r.x, y: r.y, w: r.width, h: r.height, border: parseFloat(c.borderTopWidth) }; }"""
    )
    x0, y0 = int(info["x"]) - 2, int(info["y"]) - 2
    clip = {"x": x0, "y": y0, "width": int(info["w"]) + 6, "height": int(info["h"]) + 6}
    img = Image.open(io.BytesIO(page.screenshot(clip=clip))).convert("RGB")
    ox, oy = round((info["x"] - x0) * SCALE), round((info["y"] - y0) * SCALE)
    box = (ox, oy, ox + round(info["w"] * SCALE), oy + round(info["h"] * SCALE))
    return np.asarray(img.crop(box), dtype=np.float32), info


def existing_rules() -> dict[str, str]:
    """The sheen rules already in the stylesheet, by sticker, so a partial run keeps the rest."""
    block = CSS.read_text().split(BEGIN)[1].split(END)[0]
    rules = {}
    for line in block.strip().splitlines():
        name = line.split(".wd-", 1)[1].split(" ", 1)[0]
        rules[name] = line
    return rules


def main() -> None:
    wanted = sys.argv[1:] or ON_FRONT
    unknown = [n for n in wanted if n not in ON_FRONT]
    if unknown:
        raise SystemExit(f"cannot photograph {unknown}: pick from {ON_FRONT}")
    sock = socket.socket()
    sock.bind(("127.0.0.1", 0))
    port = sock.getsockname()[1]
    sock.close()
    threading.Thread(
        target=uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, log_level="error")).run, daemon=True
    ).start()
    time.sleep(2)

    OUT.mkdir(parents=True, exist_ok=True)
    rules = existing_rules()
    with sync_playwright() as p:
        browser = p.chromium.launch()
        for name in wanted:
            shots = []
            for backdrop in ("#000", "#fff"):
                ctx = browser.new_context(viewport={"width": 1440, "height": 900}, device_scale_factor=SCALE)
                page = ctx.new_page()
                page.goto(f"http://127.0.0.1:{port}/")
                page.wait_for_timeout(1200)
                shots.append(shoot(page, name, backdrop))
                ctx.close()
            (black, info), (white, _) = shots
            alpha = np.clip(1 - (white - black).mean(axis=2) / 255, 0, 1)
            Image.fromarray(sheen(alpha), "RGBA").save(OUT / f"{name}.png", optimize=True)
            bw = round(info["border"], 2)
            inset = f"-{bw:g}px" if bw else "0"
            rules[name] = f".wd-{name} .wd-mt {{ background-image: url(/static/img/notebook/sheen/{name}.png); inset: {inset}; }}"
            print(f"{name}: {alpha.shape[1]}x{alpha.shape[0]} px, border {bw:g}px")
        browser.close()

    block = [BEGIN, *(rules[n] for n in STICKERS if n in rules), END]
    css = CSS.read_text()
    head, rest = css.split(BEGIN)
    css = head + "\n".join(block) + rest.split(END, 1)[1]
    CSS.write_text(css)


if __name__ == "__main__":
    main()
